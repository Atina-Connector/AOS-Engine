function ok = verificar_version_local(raiz, ok)
  ruta = fullfile(raiz, 'VERSION');
  if exist(ruta, 'file') ~= 2
    fprintf(2, 'FALLO: VERSION ausente\n');
    ok = false; return;
  endif
  v = strtrim(fileread(ruta));
  if strcmp(v, '0.2.0-DEV1')
    fprintf('OK   VERSION %s\n', v);
  else
    fprintf(2, 'FALLO: VERSION esperada 0.2.0-DEV1; encontrada %s\n', v);
    ok = false;
  endif
endfunction

function ok = verificar_integracion_cad_reportes_local(raiz, ok)
  ruta = fullfile(raiz, 'src', 'modulos', 'cad_topo', 'aos_aoscad_escribir.m');
  if exist(ruta, 'file') ~= 2, ok = false; return; endif
  txt = fileread(ruta);
  if isempty(strfind(txt, 'aos_aoscad_report_composition'))
    fprintf(2, 'FALLO: AOSCAD no integra composicion transversal de tablas\n'); ok = false;
  else
    fprintf('OK   AOSCAD integra composicion transversal de tablas\n');
  endif
  if isempty(strfind(txt, 'aos_aoscad_generar_recursos_visuales'))
    fprintf(2, 'FALLO: se perdio generacion de recursos visuales R16\n'); ok = false;
  else
    fprintf('OK   AOSCAD conserva recursos visuales R16\n');
  endif
  ver = fullfile(raiz, 'src', 'modulos', 'cad_topo', 'VERSION_AOSCAD.txt');
  if exist(ver, 'file') == 2
    t = fileread(ver);
    if isempty(strfind(t, 'AOSCAD-0.0.1-DEV1-R16'))
      fprintf(2, 'FALLO: AOSCAD integrado no es R16\n'); ok = false;
    else
      fprintf('OK   AOSCAD R16 preservado\n');
    endif
  endif
endfunction

