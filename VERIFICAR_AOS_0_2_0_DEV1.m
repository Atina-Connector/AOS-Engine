    'src/roadmap/aos_frame_ribbon_contract_0_2_0.json', ...
    'src/roadmap/aos_report_tables_contract_hf3_5.json'};
  if exist('jsondecode', 'builtin') ~= 5 && exist('jsondecode', 'file') ~= 2
    fprintf(2, 'FALLO: jsondecode no disponible en GNU Octave\n');
    ok = false; return;
  endif
  for i = 1:numel(archivos)
    ruta = fullfile(raiz, archivos{i});
    try
      jsondecode(fileread(ruta));
      fprintf('OK   JSON %s\n', archivos{i});
    catch err
      fprintf(2, 'FALLO JSON %s: %s\n', archivos{i}, err.message);
      ok = false;
    end_try_catch
  endfor
endfunction

function ok = verificar_octave_only_local(raiz, ok)
  mats = listar_extension_local(raiz, '.mat');
  if isempty(mats)
    fprintf('OK   arquitectura sin archivos .mat\n');
  else
    fprintf(2, 'FALLO: archivos .mat encontrados:\n');
    for i = 1:numel(mats), fprintf(2, '  %s\n', mats{i}); endfor
    ok = false;
  endif

  dups = duplicados_m_local(fullfile(raiz, 'src'));
  if isempty(dups)
    fprintf('OK   sin nombres .m duplicados dentro de src\n');
  else
    fprintf(2, 'FALLO: nombres .m duplicados dentro de src:\n');
    for i = 1:numel(dups), fprintf(2, '  %s\n', dups{i}); endfor
    ok = false;
  endif
endfunction

function ok = ejecutar_test_local(nombre, ok)
  try
    iniciar_aos(true); rehash();
    if exist(nombre, 'file') ~= 2
      fprintf(2, 'FALLO: selftest no encontrado: %s\n', nombre);
      ok = false; return;
    endif
    r = feval(nombre);
    if ~isempty(r) && logical(r)
      fprintf('OK   selftest %s\n', nombre);
    else
      fprintf(2, 'FALLO: selftest sin aprobacion: %s\n', nombre);
      ok = false;
    endif
  catch err
    fprintf(2, 'FALLO selftest %s: %s\n', nombre, err.message);
    ok = false;
  end_try_catch
endfunction

function lista = listar_extension_local(carpeta, extension)
  lista = {};
  d = dir(carpeta);
  for i = 1:numel(d)
    if strcmp(d(i).name, '.') || strcmp(d(i).name, '..'), continue; endif
    ruta = fullfile(carpeta, d(i).name);
    if d(i).isdir
      sub = listar_extension_local(ruta, extension);
      lista = [lista, sub]; %#ok<AGROW>
    else
      [~,~,e] = fileparts(d(i).name);
      if strcmpi(e, extension), lista{end+1} = ruta; endif %#ok<AGROW>
    endif
  endfor
endfunction

function dups = duplicados_m_local(carpeta)
  rutas = listar_m_local(carpeta);
  nombres = cell(1, numel(rutas));
  for i = 1:numel(rutas)
    [~, nombres{i}] = fileparts(rutas{i});
    nombres{i} = lower(nombres{i});
  endfor
  dups = {};
  unicos = unique(nombres);
  for i = 1:numel(unicos)
    idx = find(strcmp(nombres, unicos{i}));
    if numel(idx) > 1
      for j = 1:numel(idx), dups{end+1} = rutas{idx(j)}; endfor %#ok<AGROW>
    endif
  endfor
endfunction

function rutas = listar_m_local(carpeta)
  rutas = {};
  d = dir(carpeta);
  for i = 1:numel(d)
    if strcmp(d(i).name, '.') || strcmp(d(i).name, '..'), continue; endif
    ruta = fullfile(carpeta, d(i).name);
    if d(i).isdir
      rutas = [rutas, listar_m_local(ruta)]; %#ok<AGROW>
    else
      [~,~,e] = fileparts(d(i).name);
      if strcmpi(e, '.m'), rutas{end+1} = ruta; endif %#ok<AGROW>
    endif
  endfor
endfunction
